from pathlib import Path
import json
import html
root = Path(__file__).resolve().parent.parent
source = (root / 'index.html').read_text()
copy = json.loads((root / 'text-content.json').read_text())
(root / 'text-content.mjs').write_text('// Generated by scripts/prepare-pages.py from text-content.json.\nexport const displayCopy = ' + json.dumps(copy, ensure_ascii=False, indent=2) + ';\n')
for host in ['Monty', 'Haunty']:
    for strategy, contestant in [('Switch', 'female'), ('NoSwitch', 'male')]:
        folder = root / host / strategy
        folder.mkdir(parents=True, exist_ok=True)
        page = source.replace('<head>', '<head>\n  <base href="../../">', 1)
        page = page.replace('<body>', f'<body data-fixed-host="{host.lower()}" data-fixed-contestant="{contestant}">', 1)
        page = page.replace("Let's Win a Car — opening dialogue", f"Let's Win a Car — {host} / {strategy}")
        page = page.replace('<p id="game-intro"></p>', '<p id="game-intro">' + html.escape(copy['intro']) + '</p>')
        variant = copy['variants'][f'{host.lower()}-{contestant}']
        page = page.replace('<p id="variant-description"></p>', '<p id="variant-description">' + html.escape(variant) + '</p>')
        (folder / 'index.html').write_text(page)
(root / '.nojekyll').touch()
print('Prepared four fixed display pages.')
