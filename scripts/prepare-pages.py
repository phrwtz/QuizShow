from pathlib import Path
import json
import html
import hashlib
import re
root = Path(__file__).resolve().parent.parent
source = (root / 'review.html').read_text()
copy = json.loads((root / 'text-content.json').read_text())
(root / 'text-content.mjs').write_text('// Generated by scripts/prepare-pages.py from text-content.json.\nexport const displayCopy = ' + json.dumps(copy, ensure_ascii=False, indent=2) + ';\n')
modules = ['game-logic.mjs', 'playback.mjs', 'text-content.mjs', 'tally.mjs', 'timeline.mjs']
runtime = '\n\n'.join((root / name).read_text() for name in modules)
runtime += '\n\n' + re.sub(r'^import .*;\n', '', (root / 'preview.js').read_text(), flags=re.MULTILINE)
(root / 'display-runtime.mjs').write_text('// Generated by scripts/prepare-pages.py.\n' + runtime)
revision = hashlib.sha256((runtime + (root / 'preview.css').read_text()).encode()).hexdigest()[:12]
for host in ['Monty', 'Haunty']:
    for strategy, contestant in [('Switch', 'female'), ('NoSwitch', 'male')]:
        folder = root / host / strategy
        folder.mkdir(parents=True, exist_ok=True)
        page = source.replace('<head>', '<head>\n  <base href="../../">', 1)
        page = page.replace('<body>', f'<body data-fixed-host="{host.lower()}" data-fixed-contestant="{contestant}">', 1)
        page = page.replace("Let's Win a Car — opening dialogue", f"Version {1 + (2 if host == 'Haunty' else 0) + (1 if strategy == 'NoSwitch' else 0)}")
        page = page.replace('src="preview.js"', f'src="display-runtime.mjs?v={revision}"')
        page = page.replace('href="preview.css"', f'href="preview.css?v={revision}"')
        page = page.replace('<p id="game-intro"></p>', '<p id="game-intro">' + html.escape(copy['intro']) + '</p>')
        variant = copy['variants'][f'{host.lower()}-{contestant}']
        page = page.replace('<p id="variant-description"></p>', '<p id="variant-description">' + html.escape(variant) + '</p>')
        (folder / 'index.html').write_text(page)
(root / '.nojekyll').touch()
print('Prepared four fixed display pages.')
